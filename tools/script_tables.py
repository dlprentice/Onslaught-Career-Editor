"""Writes companion/OnslaughtToolkit.Godot/Levels/ScriptTables.g.cs: the names the Companion shows for the parts of a compiled
mission script, taken from this Toolkit's reference tables (tools/world_resources_decode.py).

- EventNames: the 13 events a script's entry points are indexed by (SCRIPT_EVENT_NAMES, ScriptObjectCode.cpp 0x0064fef8).
- Natives: every function a script can call, with the letters of its argument types, in the order a CALL instruction's low byte
  indexes them (gScriptFunctions, IScript.cpp 0x0052ff20): i int, f float, s string, b bool, t thing, p position, * any.

    python tools/script_tables.py --check     fail if the committed C# file is not what --write writes
    python tools/script_tables.py --write     rewrite the C# file

The generated file holds no game bytes: names of the game's own functions and events, as the decompilation lists them.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

TOOLS = Path(__file__).resolve().parent
ROOT = TOOLS.parent
sys.path.insert(0, str(TOOLS))

import world_resources_decode as wrd  # noqa: E402

OUTPUT = ROOT / "companion/OnslaughtToolkit.Godot/Levels/ScriptTables.g.cs"


def render() -> str:
    assert len(wrd.SCRIPT_EVENT_NAMES) == wrd.NUM_SCRIPT_EVENTS
    lines = [
        "// SPDX-License-Identifier: GPL-3.0-only",
        "// <auto-generated> by tools/script_tables.py from tools/world_resources_decode.py; do not edit it.",
        "// `python tools/script_tables.py --check` fails when this file is not what `--write` writes.",
        "namespace OnslaughtToolkit.Companion.Levels;",
        "",
        "/// <summary>The names of a compiled mission script's parts, as the game's tables have them (see tools/script_tables.py).</summary>",
        "public static class ScriptTables",
        "{",
        "    /// <summary>The events a script's entry points are indexed by (<c>SCRIPT_EVENT_NAMES</c>, <c>ScriptObjectCode.cpp</c> 0x0064fef8).</summary>",
        "    public static readonly string[] EventNames =",
        "    [",
    ]
    lines += [f'        "{name}",' for name in wrd.SCRIPT_EVENT_NAMES]
    lines += [
        "    ];",
        "",
        "    /// <summary>",
        "    /// Every function a script can call, in the order a CALL instruction's low byte indexes them (<c>gScriptFunctions</c>, <c>IScript.cpp</c> 0x0052ff20),",
        "    /// with the letters of its argument types: i int, f float, s string, b bool, t thing, p position, * any.",
        "    /// </summary>",
        "    public static readonly (string Name, string Parameters)[] Natives =",
        "    [",
    ]
    lines += [f'        ("{name}", "{types}"),' for name, types in wrd.SCRIPT_NATIVES]
    lines += ["    ];", "}", ""]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    text = render()
    if args.write:
        OUTPUT.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {OUTPUT.relative_to(ROOT)} ({len(text)} characters)")
        return 0
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != text:
            print(f"FAIL {OUTPUT.relative_to(ROOT)} is not what `python tools/script_tables.py --write` writes")
            return 1
        print(f"{OUTPUT.relative_to(ROOT)} is current")
        return 0
    parser.error("choose --write or --check")
    return 2


if __name__ == "__main__":
    raise SystemExit(main())
